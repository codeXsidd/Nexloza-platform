import 'board_definitions.dart';

class FirmwareConfig {
  final BoardDefinition board;
  final List<SensorDefinition> sensors;
  final List<ActuatorDefinition> actuators;
  final Map<String, int> pinAssignments;
  final String wifiSsid;
  final String deviceApiKey;

  const FirmwareConfig({
    required this.board,
    this.sensors = const [],
    this.actuators = const [],
    this.pinAssignments = const {},
    this.wifiSsid = 'YOUR_WIFI_SSID',
    this.deviceApiKey = 'YOUR_DEVICE_API_KEY',
  });
}

abstract final class CodeGenerator {
  static String generate(FirmwareConfig config) {
    final buf = StringBuffer();

    buf.writeln('// Generated by Nexloza Device Studio');
    buf.writeln('// Board: ${config.board.name}');
    buf.writeln('// Sensors: ${config.sensors.map((s) => s.name).join(", ")}');
    buf.writeln(
      '// Actuators: ${config.actuators.map((a) => a.name).join(", ")}',
    );
    buf.writeln();

    // Includes
    buf.writeln(config.board.includeHeader);
    buf.writeln('#include <PubSubClient.h>');
    buf.writeln('#include <ArduinoJson.h>');
    if (config.sensors.any((s) => s.id == 'dht22')) {
      buf.writeln('#include <DHT.h>');
    }
    if (config.sensors.any((s) => s.id == 'bme280')) {
      buf.writeln('#include <Wire.h>');
      buf.writeln('#include <Adafruit_BME280.h>');
    }
    if (config.sensors.any((s) => s.id == 'hcsr04')) {
      buf.writeln('#include <NewPing.h>');
    }
    buf.writeln();

    // Config
    buf.writeln('// ---- Configuration ----');
    buf.writeln('const char* WIFI_SSID = "${config.wifiSsid}";');
    buf.writeln('const char* WIFI_PASS = "YOUR_WIFI_PASSWORD";');
    buf.writeln('const char* MQTT_HOST = "YOUR_MQTT_HOST";');
    buf.writeln('const int   MQTT_PORT = 1883;');
    buf.writeln('const char* DEVICE_ID = "YOUR_DEVICE_ID";');
    buf.writeln('const char* API_KEY   = "${config.deviceApiKey}";');
    buf.writeln();

    // Pin definitions
    buf.writeln('// ---- Pin Definitions ----');
    for (final sensor in config.sensors) {
      final pin = config.pinAssignments[sensor.id] ?? 4;
      buf.writeln(
        '#define ${sensor.id.toUpperCase()}_PIN $pin  // ${sensor.name}',
      );
    }
    for (final actuator in config.actuators) {
      final pin = config.pinAssignments[actuator.id] ?? 2;
      buf.writeln(
        '#define ${actuator.id.toUpperCase()}_PIN $pin  // ${actuator.name}',
      );
    }
    buf.writeln();

    // MQTT topics (canonical v1 format)
    buf.writeln(
      '// ---- MQTT Topics (nexloza/v1/{org}/{project}/{device}/{channel}) ----',
    );
    buf.writeln(
      'String topicBase = String("nexloza/v1/") + ORG_ID + "/" + PROJECT_ID + "/" + DEVICE_ID;',
    );
    buf.writeln('String telemetryTopic = topicBase + "/telemetry";');
    buf.writeln('String commandTopic = topicBase + "/command";');
    buf.writeln('String statusTopic = topicBase + "/status";');
    buf.writeln();

    // Objects
    buf.writeln('WiFiClient wifiClient;');
    buf.writeln('PubSubClient mqtt(wifiClient);');
    for (final sensor in config.sensors) {
      if (sensor.id == 'dht22') {
        buf.writeln('DHT dht(${sensor.id.toUpperCase()}_PIN, DHT22);');
      }
      if (sensor.id == 'bme280') {
        buf.writeln('Adafruit_BME280 bme;');
      }
      if (sensor.id == 'hcsr04') {
        buf.writeln(
          'NewPing sonar(${sensor.id.toUpperCase()}_PIN, ${sensor.id.toUpperCase()}_PIN + 1, 400);',
        );
      }
    }
    buf.writeln();
    buf.writeln('unsigned long lastTelemetry = 0;');
    buf.writeln('const unsigned long TELEMETRY_INTERVAL = 10000;');
    buf.writeln();

    // WiFi connect
    buf.writeln('void connectWiFi() {');
    buf.writeln('  WiFi.begin(WIFI_SSID, WIFI_PASS);');
    buf.writeln('  Serial.print("Connecting to WiFi");');
    buf.writeln('  while (WiFi.status() != WL_CONNECTED) {');
    buf.writeln('    delay(500);');
    buf.writeln('    Serial.print(".");');
    buf.writeln('  }');
    buf.writeln('  Serial.println(" Connected!");');
    buf.writeln('}');
    buf.writeln();

    // MQTT callback
    buf.writeln(
      'void mqttCallback(char* topic, byte* payload, unsigned int length) {',
    );
    buf.writeln('  String msg;');
    buf.writeln(
      '  for (unsigned int i = 0; i < length; i++) msg += (char)payload[i];',
    );
    buf.writeln('  Serial.print("Command: "); Serial.println(msg);');
    buf.writeln();
    buf.writeln('  JsonDocument doc;');
    buf.writeln('  deserializeJson(doc, msg);');
    buf.writeln('  const char* cmd = doc["command"];');
    buf.writeln();
    for (final actuator in config.actuators) {
      buf.writeln('  if (String(cmd) == "set_${actuator.id}") {');
      if (actuator.type == 'Switch') {
        buf.writeln('    bool state = doc["value"] | false;');
        buf.writeln(
          '    digitalWrite(${actuator.id.toUpperCase()}_PIN, state ? HIGH : LOW);',
        );
      } else {
        buf.writeln('    int value = doc["value"] | 0;');
        buf.writeln(
          '    analogWrite(${actuator.id.toUpperCase()}_PIN, value);',
        );
      }
      buf.writeln('  }');
    }
    buf.writeln('}');
    buf.writeln();

    // MQTT connect
    buf.writeln('void connectMQTT() {');
    buf.writeln('  mqtt.setServer(MQTT_HOST, MQTT_PORT);');
    buf.writeln('  mqtt.setCallback(mqttCallback);');
    buf.writeln('  while (!mqtt.connected()) {');
    buf.writeln('    Serial.print("Connecting to MQTT...");');
    buf.writeln('    if (mqtt.connect(DEVICE_ID, DEVICE_ID, API_KEY)) {');
    buf.writeln('      Serial.println(" Connected!");');
    buf.writeln('      mqtt.subscribe(commandTopic.c_str());');
    buf.writeln(
      '      mqtt.publish(statusTopic.c_str(), "{\\"status\\":\\"online\\"}");',
    );
    buf.writeln('    } else {');
    buf.writeln(
      '      Serial.print(" Failed, rc="); Serial.println(mqtt.state());',
    );
    buf.writeln('      delay(5000);');
    buf.writeln('    }');
    buf.writeln('  }');
    buf.writeln('}');
    buf.writeln();

    // Setup
    buf.writeln('void setup() {');
    buf.writeln('  Serial.begin(115200);');
    buf.writeln('  Serial.println("Nexloza Device Starting...");');
    buf.writeln();
    for (final actuator in config.actuators) {
      buf.writeln('  pinMode(${actuator.id.toUpperCase()}_PIN, OUTPUT);');
    }
    for (final sensor in config.sensors) {
      if (sensor.id == 'dht22') buf.writeln('  dht.begin();');
      if (sensor.id == 'bme280') buf.writeln('  bme.begin(0x76);');
      if (sensor.id == 'pir') {
        buf.writeln('  pinMode(${sensor.id.toUpperCase()}_PIN, INPUT);');
      }
    }
    buf.writeln();
    buf.writeln('  connectWiFi();');
    buf.writeln('  connectMQTT();');
    buf.writeln('}');
    buf.writeln();

    // Loop
    buf.writeln('void loop() {');
    buf.writeln('  if (!mqtt.connected()) connectMQTT();');
    buf.writeln('  mqtt.loop();');
    buf.writeln();
    buf.writeln('  if (millis() - lastTelemetry >= TELEMETRY_INTERVAL) {');
    buf.writeln('    lastTelemetry = millis();');
    buf.writeln('    JsonDocument doc;');
    buf.writeln();
    for (final sensor in config.sensors) {
      for (final reading in sensor.readings) {
        if (sensor.id == 'dht22' && reading == 'temperature') {
          buf.writeln('    doc["temperature"] = dht.readTemperature();');
        } else if (sensor.id == 'dht22' && reading == 'humidity') {
          buf.writeln('    doc["humidity"] = dht.readHumidity();');
        } else if (sensor.id == 'bme280' && reading == 'temperature') {
          buf.writeln('    doc["temperature"] = bme.readTemperature();');
        } else if (sensor.id == 'bme280' && reading == 'humidity') {
          buf.writeln('    doc["humidity"] = bme.readHumidity();');
        } else if (sensor.id == 'bme280' && reading == 'pressure') {
          buf.writeln('    doc["pressure"] = bme.readPressure() / 100.0;');
        } else if (sensor.id == 'soil_moisture') {
          buf.writeln(
            '    doc["soil_moisture"] = map(analogRead(${sensor.id.toUpperCase()}_PIN), 4095, 0, 0, 100);',
          );
        } else if (sensor.id == 'hcsr04') {
          buf.writeln('    doc["distance"] = sonar.ping_cm();');
        } else if (sensor.id == 'pir') {
          buf.writeln(
            '    doc["motion"] = digitalRead(${sensor.id.toUpperCase()}_PIN);',
          );
        }
      }
    }
    buf.writeln();
    buf.writeln('    char payload[256];');
    buf.writeln('    serializeJson(doc, payload);');
    buf.writeln('    mqtt.publish(telemetryTopic.c_str(), payload);');
    buf.writeln('    Serial.print("Telemetry: "); Serial.println(payload);');
    buf.writeln('  }');
    buf.writeln('}');

    return buf.toString();
  }
}
